/** The comment every generated shader opens with: what it is, its author, its licence. */
function header(what, edit = 'that module') {
    return [
        `MWSR — MoonlightWeb Super Resolution: ${what}.`,
        'Copyright (c) 2026 Bruno Martin <brunoocto@gmail.com>',
        'SPDX-License-Identifier: MIT',
        '',
        'Generated by mwsr/generate.mjs from frontend/js/stream/renderers/MwsrShader.js',
        `in https://github.com/linckosz/moonlight-web: edit ${edit}, not this file.`,
        'Bindings, parameters and examples: mwsr/README.md.',
        '',
        ...MIT.split('\n'),
    ]
        .map((l) => ('// ' + l).trimEnd())
        .join('\n');
}

// WebGlRenderer's full-screen triangle: three vertices from gl_VertexID, v
// down (the texture's first row is the top of the picture), which the GLSL
// fragment texts expect (their dFdy is negated for it).
const VERT = `
out vec2 vUv;
void main() {
    vec2 uv = vec2(float((gl_VertexID << 1) & 2), float(gl_VertexID & 2));
    vUv = uv;
    gl_Position = vec4(uv * vec2(2.0, -2.0) + vec2(-1.0, 1.0), 0.0, 1.0);
}
`;

// A JavaScript number as a C++ literal: integers stay integers, the rest keep
// every digit JavaScript prints (the JavaScript side computes in doubles).
const cppNumber = (v) => (Number.isInteger(v) ? String(v) + '.0' : String(v));

/**
 * cpp/mwsr.h: the CPU side of a native renderer, the twin of the module's
 * mwsrRegime(), mwsrLaw() and mwsrUniforms(), its tables written from
 * the module's own so that the defaults cannot drift apart.
 * @returns {string}
 */
function cppHeader() {
    const grid = (table) =>
        table.map(([min, taps, r]) => `    {${cppNumber(min)}, ${taps}, ${cppNumber(r)}},`).join('\n');
    const consts = Object.entries(MWSR_OVERRIDE_SPEC)
        .map(([k, [t, v]]) => `    {"${k}", ${t === 'u32' ? 'true' : 'false'}, ${cppNumber(v)}},`)
        .join('\n');
    const z = MWSR_ZONE;
    const lawTable = (t) =>
        Object.entries(t)
            .map(([k, c]) => `    {${c.map(cppNumber).join(', ')}},  // ${k}`)
            .join('\n');
    return `${header('the CPU side for a native renderer (C++17, header only)', 'generate.mjs or the tables of that module')}
//
// What it gives a Direct3D 11 or 12 renderer (or any other), with no
// dependency: the mode a frame of inW x inH drawn at outW x outH takes and its
// shader file (regime, shaderFile), the kernel's values for those sizes (law),
// the 96 bytes of the constant buffer at register b0 (constants), and the
// defines to compile the shader with (defines), each the twin of the JavaScript
// module's function of that name.
// example_d3d11.cpp shows them at work.

#pragma once

#include <algorithm>
#include <cmath>
#include <cstdio>
#include <optional>
#include <string>
#include <vector>

namespace mwsr {

// The mode of one frame (mwsrRegime()).
enum class Mode { Copy, Up, Down };

struct Regime {
    Mode mode = Mode::Copy;
    int taps = 0;              // Up: 5 (the flat path's); Down: the grid's samples, 1, 4, 9 or 16
    double rDown = 0.0;        // Down: MWSR_R_DOWN
    unsigned linearLight = 0;  // Down: MWSR_LINEAR_LIGHT
};

// The constant buffer, register b0: the shader's cbuffer MwsrConstants, float for float.
struct Constants {
    float texel[2];        // 1 / inW, 1 / inH
    float scale[2];        // outW / inW, outH / inH
    float dims[2];         // inW, inH
    float across[2];       // the distance of the across taps, as a share of the input
    float tau;             // the vote's threshold, luma per input texel
    float fc;              // the flat path cubic's C
    float wacross;         // the weight of each across tap, negative: it sharpens
    float kblend;          // 1 / (1 + 2 wacross), the blend's inverse divisor
    float zoneCentre[2];   // the gaze zone, and what it moves, read only with MWSR_GAZE 1
    float zoneHalfAxes[2];
    float zoneRing;
    float zoneTau;
    float zoneSharp;
    float gaze;            // its weight, 0 without one
    float sharp;           // the sharpness
    float strength;        // the kernel's strength: 0 at 1:1, 1 from kFullScale on
    float wmin;            // the most negative weight of an across tap
    float pad1;
};
static_assert(sizeof(Constants) == 96, "the constant buffer is 24 floats");

// The gaze zone: its centre and half-axes as fractions of the picture, the
// ring's width as a fraction of the half-axes, its threshold and sharpness.
struct Zone {
    double cx = ${cppNumber(z.cx)}, cy = ${cppNumber(z.cy)};
    double rx = ${cppNumber(z.rx)}, ry = ${cppNumber(z.ry)};
    double ring = ${cppNumber(z.ring)};
    double tau = ${cppNumber(z.tau)}, sharp = ${cppNumber(z.sharp)};
};

// The law's coefficients (mwsrLaw()), value = c0 + c1 x + c2 x^2 + c3 x^3 + c4 x^4 + c5 y + c6 x y,
// in the order of the struct Law below, and the ranges it holds at their ends.
constexpr double kLawPlain[5][7] = {
${lawTable(MWSR_LAW.plain)}
};
constexpr double kLawZones[5][7] = {
${lawTable(MWSR_LAW.zones)}
};
constexpr double kLawScaleMin = ${cppNumber(MWSR_LAW.scale[0])}, kLawScaleMax = ${cppNumber(MWSR_LAW.scale[1])};
constexpr double kLawHeightMin = ${cppNumber(MWSR_LAW.height[0])}, kLawHeightMax = ${cppNumber(MWSR_LAW.height[1])};
constexpr double kLawHeightRef = ${cppNumber(MWSR_LAW.heightRef)};

// The weight of each tap across the edge, negated, per unit of sharpness, and the
// scale from which the kernel is at full strength.
constexpr double kWeightAcross = ${cppNumber(MWSR_CONSTANTS.W_ACROSS)};
constexpr double kFullScale = ${cppNumber(MWSR_CONSTANTS.S_FULL)};

// The reduction's grids, by the smallest scale they serve: {minimum scale, samples, R_DOWN}.
struct Grid {
    double minScale;
    int taps;
    double rDown;
};
// The light made by the shader (LINEAR_LIGHT 1)
constexpr Grid kDownGrids[] = {
${grid(MWSR_DOWN_TAPS)}
};
// Through sRGB views (LINEAR_LIGHT 0), or on a feed in linear light (3)
constexpr Grid kDownGridsSrgb[] = {
${grid(MWSR_DOWN_TAPS_SRGB)}
};

// Every constant of the shaders, with its default; a define MWSR_<name> sets it.
struct Constant {
    const char* name;
    bool isUint;
    double value;
};
constexpr Constant kConstants[] = {
${consts}
};

// The mode, the grid, its span and its light for a frame (mwsrRegime()).
// srgbViews: the input is read through an sRGB view and the output written
// into one (DXGI_FORMAT_*_UNORM_SRGB views of a TYPELESS texture), so the
// hardware makes the linear light; linearFeed: the input already holds it.
inline Regime regime(int inW, int inH, int outW, int outH, bool srgbViews = false, bool linearFeed = false)
{
    if (inW == outW && inH == outH)
        return {Mode::Copy, 0, 0.0, 0};
    const double s = std::min(double(outW) / inW, double(outH) / inH);
    if (s >= 1.0)
        return {Mode::Up, 5, 0.0, 0};
    const Grid* table = srgbViews || linearFeed ? kDownGridsSrgb : kDownGrids;
    const unsigned light = srgbViews ? 0u : linearFeed ? 3u : 1u;
    for (int i = 0; i < 3; ++i)
        if (s >= table[i].minScale)
            return {Mode::Down, table[i].taps, table[i].rDown, light};
    return {Mode::Down, table[2].taps, table[2].rDown, light};
}

// The shader file of a regime, in this folder's hlsl/.
inline std::string shaderFile(const Regime& r, bool half = false)
{
    if (r.mode == Mode::Down)
        return "mwsr-down-" + std::to_string(r.taps) + ".hlsl";
    return half ? "mwsr-up-half.hlsl" : "mwsr-up.hlsl";
}

// The kernel's values for an input of inW x inH drawn at outW x outH (mwsrLaw()):
// each a curve over the scale (the smaller axis) and the surface's height at
// 16:9 for the same area. zones: the table of the frames read with the native
// host's zones.
struct Law {
    double tau, sharp, wmin, racross, fc;
};

inline Law law(int inW, int inH, int outW, int outH, bool zones = false)
{
    auto hold = [](double v, double lo, double hi) { return std::min(std::max(v, lo), hi); };
    const double s = std::min(double(outW) / inW, double(outH) / inH);
    const double x = std::log(hold(s, kLawScaleMin, kLawScaleMax));
    const double h = std::sqrt(double(outW) * outH * 9.0 / 16.0);
    const double y = std::log(hold(h, kLawHeightMin, kLawHeightMax) / kLawHeightRef);
    const double (*t)[7] = zones ? kLawZones : kLawPlain;
    auto value = [&](int i) { return t[i][0] + x * (t[i][1] + x * (t[i][2] + x * (t[i][3] + x * t[i][4]))) + y * (t[i][5] + t[i][6] * x); };
    return {value(0), value(1), value(2), value(3), value(4)};
}

struct Options {
    bool zones = false;  // the law's table of the frames read with the native host's zones
    // a value named here replaces the law's
    std::optional<double> tau, sharp, wmin, racross, fc, sfull;
    double gaze = 0.0;  // 0 to 1, read only with MWSR_GAZE 1
    Zone zone;
};

// The constant buffer for an input of inW x inH drawn at outW x outH (mwsrUniforms()).
inline Constants constants(int inW, int inH, int outW, int outH, const Options& o = {})
{
    const Law l = law(inW, inH, outW, outH, o.zones);
    // a ring of no width would put the smoothstep's two edges together
    const double ring = std::max(o.zone.ring, 1e-3);
    Constants c{};
    c.texel[0] = float(1.0 / inW);
    c.texel[1] = float(1.0 / inH);
    c.scale[0] = float(double(outW) / inW);
    c.scale[1] = float(double(outH) / inH);
    c.dims[0] = float(inW);
    c.dims[1] = float(inH);
    const double racross = o.racross.value_or(l.racross);
    c.across[0] = float(racross / inW);
    c.across[1] = float(racross / inH);
    c.tau = float(o.tau.value_or(l.tau));
    c.fc = float(o.fc.value_or(l.fc));
    const double sharp = o.sharp.value_or(l.sharp);
    // the kernel's strength: none at 1:1 (the renderer copies the frame there), full from kFullScale on
    const double smin = std::min(double(outW) / inW, double(outH) / inH);
    const double strength = std::min(std::max((smin - 1.0) / (o.sfull.value_or(kFullScale) - 1.0), 0.0), 1.0);
    // the blend divides by 1 + 2 wacross: a named wmin stops short of 0
    const double wmin = std::max(o.wmin.value_or(l.wmin), -0.49);
    const double wacross = std::max(-kWeightAcross * sharp * strength, wmin);
    c.wacross = float(wacross);
    c.kblend = float(1.0 / (1.0 + 2.0 * wacross));
    c.zoneCentre[0] = float(o.zone.cx);
    c.zoneCentre[1] = float(o.zone.cy);
    c.zoneHalfAxes[0] = float(o.zone.rx);
    c.zoneHalfAxes[1] = float(o.zone.ry);
    c.zoneRing = float(ring);
    c.zoneTau = float(o.zone.tau);
    c.zoneSharp = float(o.zone.sharp);
    c.gaze = float(std::min(std::max(o.gaze, 0.0), 1.0));
    c.sharp = float(sharp);
    c.strength = float(strength);
    c.wmin = float(wmin);
    return c;
}

// A define to compile a shader with: MWSR_<name>=<value>.
struct Define {
    std::string name;
    std::string value;
};

inline std::string number(double v)
{
    char s[32];
    std::snprintf(s, sizeof s, "%.9g", v);
    return s;
}

// The defines of a regime's shader: a reduction's span and light, or, for the
// upscale, the constants given (by name, without the prefix) over the
// defaults, such as {{"CHROMA444", "1"}} on a 4:4:4 stream.
inline std::vector<Define> defines(const Regime& r, const std::vector<Define>& up = {})
{
    std::vector<Define> d;
    if (r.mode == Mode::Down) {
        d.push_back({"MWSR_R_DOWN", number(r.rDown)});
        d.push_back({"MWSR_LINEAR_LIGHT", std::to_string(r.linearLight)});
    } else {
        for (const Define& x : up)
            d.push_back({"MWSR_" + x.name, x.value});
    }
    return d;
}

}  // namespace mwsr
`;
}

/** A GLSL text with the header after its `#version` line, which must come first. */
function glsl(what, text) {
    const nl = text.indexOf('\n');
    return text.slice(0, nl + 1) + header(what) + '\n' + text.slice(nl + 1);
}

/**
 * Every file of the folder this script writes, path → content.
 * @returns {Object<string, string>}
 */
export function mwsrDist() {
    const files = {
        'js/MwsrShader.js': readFileSync(SOURCE, 'utf8'),
        'wgsl/mwsr-up.wgsl':
            header('the upscale (output larger than the input), WGSL') + '\n' + mwsrWgsl(),
        'wgsl/mwsr-up-f16.wgsl':
            header("the upscale's edge path in f16 (needs 'shader-f16'), WGSL") +
            '\n' +
            mwsrWgsl({ half: true }),
        'glsl/mwsr.vert': glsl(
            'the full-screen triangle of every fragment text, GLSL ES 3.00',
            '#version 300 es' + VERT,
        ),
        'glsl/mwsr-up.frag': glsl('the upscale, GLSL ES 3.00', mwsrGlsl()),
        'hlsl/mwsr-up.hlsl':
            header('the upscale, HLSL (Direct3D 11 with FXC, 12 with DXC)') + '\n' + mwsrHlsl(),
        'hlsl/mwsr-up-half.hlsl':
            header("the upscale's edge path in min16float, HLSL") + '\n' + mwsrHlsl({ half: true }),
        'cpp/mwsr.h': cppHeader(),
    };
    for (const taps of [1, 4, 9, 16]) {
        const k = Math.sqrt(taps);
        files[`wgsl/mwsr-down-${taps}.wgsl`] =
            header(`the reduction (output smaller than the input), ${k}×${k} samples, WGSL`) +
            '\n' +
            mwsrWgsl({ mode: 'down', taps });
        files[`hlsl/mwsr-down-${taps}.hlsl`] =
            header(`the reduction, ${k}×${k} samples, HLSL`) +
            '\n' +
            mwsrHlsl({ mode: 'down', taps });
    }
    // WebGL2 draws into no sRGB view: the reduction's software light and its
    // grids (MWSR_DOWN_TAPS), their span and light baked in.
    for (const [, taps, rDown] of MWSR_DOWN_TAPS) {
        const k = Math.sqrt(taps);
        files[`glsl/mwsr-down-${taps}.frag`] = glsl(
            `the reduction, ${k}×${k} samples, GLSL ES 3.00`,
            mwsrGlsl({ mode: 'down', taps, overrides: { R_DOWN: rDown, LINEAR_LIGHT: 1 } }),
        );
    }
    return files;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const check = process.argv.includes('--check');
    let stale = 0;
    for (const [path, text] of Object.entries(mwsrDist())) {
        const file = join(HERE, path);
        let now = null;
        try {
            // a Windows checkout may have turned the line ends into CRLF
            now = readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
        } catch {
            // not written yet
        }
        if (now === text.replace(/\r\n/g, '\n')) continue;
        stale++;
        if (check) {
            console.log('stale: mwsr/' + path);
        } else {
            mkdirSync(dirname(file), { recursive: true });
            writeFileSync(file, text);
            console.log('wrote mwsr/' + path);
        }
    }
    if (check && stale) process.exit(1);
    if (!stale) console.log('mwsr/: up to date');
}
